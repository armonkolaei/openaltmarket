import { expect, test } from '@playwright/test';

test('user can register, submit, and see submission in My Submissions', async ({ page }) => {
  const nonce = Date.now();
  const email = `openalt+${nonce}@example.com`;
  const password = `StrongPass!${nonce}`;

  await page.goto('/register');
  await page.getByLabel('Display name').fill('Playwright User');
  await page.getByLabel('Email').fill(email);
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Register' }).click();

  await expect(page.getByRole('heading', { name: 'Dashboard' })).toBeVisible();

  await page.getByLabel('App name').fill('WorthGrid Test');
  await page.getByLabel('Description').fill('A test submission generated by Playwright for local verification.');
  await page.getByLabel('Website URL').fill('https://worthgrid.com');
  await page.getByLabel('Alternatives to').fill('wealthica.com');
  await page.getByLabel('Keywords').fill('finance, budgeting, net worth');
  await page.getByRole('button', { name: 'Submit Suggestion' }).click();

  await expect(page.getByText('Submission received and queued for admin review.')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'My Submissions' })).toBeVisible();
  await expect(page.getByText('WorthGrid Test')).toBeVisible();
  await expect(page.getByText('pending')).toBeVisible();
});